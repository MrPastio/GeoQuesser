const extentCache = {};
// Габарит региона и масштаб очков: на 1/10 диагонали региона даётся ~37% от максимума.
export function regionExtent(key) {
  if (extentCache[key]) return extentCache[key];
  const boxes = REGIONS[key].boxes;
  const minLon = Math.min(...boxes.map((x) => x.b[0])), minLat = Math.min(...boxes.map((x) => x.b[1]));
  const maxLon = Math.max(...boxes.map((x) => x.b[2])), maxLat = Math.max(...boxes.map((x) => x.b[3]));
  const rad = Math.PI / 180;
  const midLat = (minLat + maxLat) / 2;
  const dx = (maxLon - minLon) * 111.32 * Math.cos(midLat * rad), dy = (maxLat - minLat) * 110.57;
  const diag = Math.min(Math.hypot(dx, dy), 20000);
  extentCache[key] = { minLon, minLat, maxLon, maxLat, scaleKm: key === 'world' ? 2000 : diag / 10 };
  return extentCache[key];
}
